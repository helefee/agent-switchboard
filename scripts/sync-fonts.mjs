import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sheets = [];
for (const weight of [400, 600, 700]) {
  const source = await readFile(require.resolve(`@fontsource/noto-sans-sc/${weight}.css`), "utf8");
  let faces = 0;
  const sheet = source.replace(
    /src:\s*url\(\.\/files\/([^\s)]+\.woff2)\)\s*format\('woff2'\),\s*url\([^;]+;/g,
    (_source, name) => {
      faces += 1;
      return `src: url("@fontsource/noto-sans-sc/files/${name}") format("woff2");`;
    },
  );
  if (faces === 0 || /\.woff["')]/.test(sheet)) {
    throw new Error(`Unexpected Noto Sans SC ${weight} stylesheet; font generation stopped.`);
  }
  sheets.push(sheet);
}
await writeFile(new URL("../src/styles/fonts.css", import.meta.url),
  "/* Generated by scripts/sync-fonts.mjs. Preserve the upstream Unicode ranges and OFL font license. */\n"
    + sheets.join("\n"));
